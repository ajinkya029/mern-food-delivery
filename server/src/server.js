import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import connectDB from './config/db.js';
import authRoutes from './routes/authRoutes.js';
import restaurantRoutes from './routes/restaurantRoutes.js';
import menuRoutes from './routes/menuRoutes.js';
import orderRoutes from './routes/orderRoutes.js';
const app = express();
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' }));
app.use(express.json({ limit: '1mb' }));
app.get('/api/health', (req, res) => res.json({ status: 'ok', service: 'QuickBite API' }));
app.use('/api/auth', authRoutes); app.use('/api/restaurants', restaurantRoutes); app.use('/api/menu', menuRoutes); app.use('/api/orders', orderRoutes);
app.use((req, res) => res.status(404).json({ message: 'Endpoint not found.' }));
app.use((err, req, res, next) => { console.error(err); res.status(err.status || 500).json({ message: err.message || 'Server error.' }); });
const port = process.env.PORT || 5000;
connectDB().then(() => app.listen(port, () => console.log(`QuickBite API listening on ${port}`))).catch(err => { console.error(err); process.exit(1); });
